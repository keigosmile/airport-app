// ふつうの画面（SVG）：色はCSS側で決める（.ic-s .ic-a .ic-A .ic-f .ic-o）
function iconSvg(key) {
  var sp = ICON_SPECS[key] || [];
  return '<svg class="icon" viewBox="0 0 48 48" aria-hidden="true" focusable="false">' + sp.map(function (p) { return '<path class="ic-' + p[0] + '" d="' + p[1] + '"/>'; }).join("") + "</svg>";
}
// シェア画像（canvas）
function drawIcon(g, key, x, y, size, ink, acc) {
  g.save(); g.translate(x, y); g.scale(size / 48, size / 48);
  g.lineWidth = 2.3; g.lineCap = "round"; g.lineJoin = "round";
  (ICON_SPECS[key] || []).forEach(function (p) {
    var path = new Path2D(p[1]);
    if (p[0] === "s") { g.lineWidth = 2.3; g.strokeStyle = ink; g.stroke(path); }
    else if (p[0] === "k") { g.lineWidth = 1.6; g.strokeStyle = ink; g.stroke(path); }
    else if (p[0] === "a") { g.lineWidth = 2.3; g.strokeStyle = acc; g.stroke(path); }
    else if (p[0] === "A") { g.fillStyle = acc; g.fill(path); }
    else if (p[0] === "o") { g.globalAlpha = 0.45; g.fillStyle = acc; g.fill(path); g.globalAlpha = 1; }
    else { g.fillStyle = ink; g.fill(path); }
  });
  g.restore();
}
